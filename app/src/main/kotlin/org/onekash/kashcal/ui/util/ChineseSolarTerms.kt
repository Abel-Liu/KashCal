private val solarTermDays by lazy {
    SOLAR_TERM_DAYS.trim().lineSequence().associate { row ->
        val fields = row.split(' ')
        fields.first().toInt() to fields.drop(1).map(String::toInt).toIntArray()
    }
}

internal fun chineseSolarTerm(date: LocalDate): String? {
    val days = solarTermDays[date.year] ?: return null
    val index = (date.monthValue - 1) * 2
    return when (date.dayOfMonth) {
        days[index] -> solarTermNames[index]
        days[index + 1] -> solarTermNames[index + 1]
        else -> null
    }
}

